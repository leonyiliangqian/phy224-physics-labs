import numpy as np
from scipy.optimize import curve_fit
import matplotlib.pyplot as plt


# Did not end up using this, but imma keep it in the code.
def power_law_model(x, a, b, c):
    """
    Power-law model function: f(x) = ax^b + c, calculates y-values based
    on the power-law model.
    """
    return a * (x ** b) + c


# Defining the quadratic model
def quadratic_model(x, a, b, c):
    """
    Quadratic model function: f(x) = ax^2 + bx + c, calculates y-values based
    on the quadratic model.
    """
    return a * (x**2) + b * x + c


# Defining the chi squared function
def calculate_chi_squared(observed, expected, uncertainties):
    """
    Calculate the chi-squared statistic.
    """
    return np.sum(((observed - expected) / uncertainties) ** 2)


# Defining the reduced chi squared function
def calculate_reduced_chi_squared(chi_squared, num_data_points, num_parameters):
    """
    Calculate the reduced chi-squared statistic.
    """
    degrees_of_freedom = num_data_points - num_parameters
    return chi_squared / degrees_of_freedom


# Reading the data
data = np.loadtxt("co2_annmean_mlo.csv", comments='#', delimiter=',', skiprows=44)
year_num = data[:, 0]  # Extract the year
emission_num = data[:, 1]  # Extract CO2 measurements
uncertainty_num = data[:, 2]  # Extract uncertainties


# Fitting the model to the observations
popt, pcov = curve_fit(quadratic_model, year_num, emission_num,
                       sigma=uncertainty_num, absolute_sigma=True)
a, b, c = popt
param_uncertainties = np.sqrt(np.diag(pcov))

# Model predictions using the parameters generated by curve_fit function
fitted_emission = quadratic_model(year_num, a, b, c)

# Plot the dataset with error bars and the fitted model
plt.figure()
plt.errorbar(year_num, emission_num, yerr=uncertainty_num, fmt='o',
             label='Observed CO2 levels')
plt.plot(year_num, fitted_emission, label=f'Fitted model')
plt.xlabel('Year')
plt.ylabel('CO2 levels (ppm)')
plt.title('CO2 Levels and Quadratic Fit')
plt.legend()
plt.show()

# Characterize the fit
residuals = emission_num - fitted_emission
chi_squared = calculate_chi_squared(emission_num, fitted_emission,
                                    uncertainty_num)
reduced_chi_squared = calculate_reduced_chi_squared(
    chi_squared, len(emission_num), len(pcov))
print(f"Reduced chi_squared: {reduced_chi_squared:.2f}")

# Plot the residuals
plt.figure()
plt.plot(year_num, residuals, 'o', label='Residuals')
plt.axhline(0, color='r', linestyle='--')
plt.xlabel('Year')
plt.ylabel('Residuals (ppm)')
plt.title('Residuals of the Quadratic Fit')
plt.legend()
plt.show()

# Predict CO2 levels in 1960 and 2060
year_1960 = 1960
year_2060 = 2060
predicted_1960 = quadratic_model(year_1960, a, b, c)
predicted_2060 = quadratic_model(year_2060, a, b, c)
uncertainty_1960 = np.sqrt((param_uncertainties[0] * (year_1960 ** 2)) ** 2 + (param_uncertainties[1] * year_1960) ** 2 + param_uncertainties[2] ** 2)
uncertainty_2060 = np.sqrt((param_uncertainties[0] * (year_2060 ** 2)) ** 2 + (param_uncertainties[1] * year_2060) ** 2 + param_uncertainties[2] ** 2)

print(f"Predicted CO2 level in 1960: {predicted_1960:.2f} ± {uncertainty_1960:.2f} ppm")
print(f"Predicted CO2 level in 2060: {predicted_2060:.2f} ± {uncertainty_2060:.2f} ppm")

# Plot the prediction
years_to_predict = np.arange(1960, 2061, 1)
predicted_values = quadratic_model(years_to_predict, a, b, c)

plt.figure()
plt.plot(year_num, emission_num, 'o', label='Observed CO2 levels')
plt.plot(years_to_predict, predicted_values, '-', label='Quadratic Model Prediction')
plt.xlabel('Year')
plt.ylabel('CO2 levels (ppm)')
plt.title('CO2 Levels Prediction (1960 - 2060) with Quadratic Fit')
plt.legend()
plt.show()
